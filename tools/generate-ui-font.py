#!/usr/bin/env python3
"""Bake the few Czech UI labels and digits; no font engine is needed on ESP32."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parents[1]
font_path = '/System/Library/Fonts/Supplemental/Arial.ttf'
items = [('title', 'Nastavení', 32), ('label', 'Jas', 20), ('luminous', 'Svítivost pixelů', 20), ('glow', 'Glow', 20), ('save', 'Uložit', 23), ('saving', 'Ukládání…', 23), ('savePosition', 'Ukládat pozici', 22), ('reset', 'Reset', 22), ('resetReady', 'Reset připraven', 16), ('error', 'Uložení selhalo', 16)]
items += [('digit'+str(i), str(i), 26) for i in range(10)] + [('percent', '%', 18)]
out = ['// Generated by tools/generate-ui-font.py; rasterized UI text only.', '#pragma once', '#include <cstdint>', 'namespace arose::uiassets {', 'struct Glyph { int width, height; const uint8_t* pixels; };']
for name, text, size in items:
    font = ImageFont.truetype(font_path, size)
    box = font.getbbox(text)
    im = Image.new('L', (box[2]-box[0], box[3]-box[1]))
    ImageDraw.Draw(im).text((-box[0],-box[1]),text,font=font,fill=255)
    data = list(im.tobytes())
    out.append('inline constexpr uint8_t '+name+'Pixels[] = {')
    out += [','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32)]
    out += ['};', f'inline constexpr Glyph {name} = {{{im.width},{im.height},{name}Pixels}};']
out += ['inline constexpr Glyph digits[] = {' + ','.join('digit'+str(i) for i in range(10)) + '};', '}']
(root/'ARoseWaveShare'/'UiAssets.h').write_text('\n'.join(out)+'\n')
print('UI labels generated.')
